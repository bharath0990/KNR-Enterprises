async function seed() {
  console.log('--- SEEDING 5 CATEGORIES & 22 NEW PRODUCTS ---');

  // 1. Ensure Categories exist
  console.log('\n[1/3] Upserting 5 Categories into Supabase categories table...');
  for (const cat of CATEGORIES_TO_ENSURE) {
    const { error } = await supabase.from('categories').upsert(cat, { onConflict: 'id' });
    if (error) {
      console.error(`Failed to upsert category ${cat.name}:`, error.message);
    } else {
      console.log(`✓ Category verified: ${cat.name}`);
    }
  }

  // 2. Insert the 22 new products without overwriting existing ones
  console.log('\n[2/3] Upserting 22 new products into Supabase products table...');
  let successCount = 0;
  for (const prod of NEW_PRODUCTS) {
    const { error } = await supabase.from('products').upsert(prod, { onConflict: 'id' });
    if (error) {
      console.error(`Failed to insert product [${prod.sku}] ${prod.name}:`, error.message);
    } else {
      console.log(`✓ Product [${prod.sku}] ${prod.name} (₹${prod.price.toLocaleString('en-IN')}) -> Category: ${prod.category} | Availability: ${prod.availability}`);
      successCount++;
    }
  }
  console.log(`\nSuccessfully inserted/verified ${successCount} / ${NEW_PRODUCTS.length} products.`);

  // 3. Verification check
  console.log('\n[3/3] Verifying database records...');
  const { data: allProds, error: verifyErr } = await supabase
    .from('products')
    .select('id, name, sku, price, category, availability, is_active')
    .order('created_at', { ascending: false });

  if (verifyErr) {
    console.error('Failed to verify products:', verifyErr.message);
  } else {
    console.log(`Total products in database: ${allProds.length} (Expected: 34)`);
    const newItems = allProds.filter((p) => NEW_PRODUCTS.some((np) => np.id === p.id));
    console.log(`Verified new products count: ${newItems.length} / 22`);
    newItems.forEach((p, idx) => {
      console.log(`  ${idx + 1}. [${p.sku}] ${p.name} - ₹${p.price} [${p.category}] - ${p.availability} (Active: ${p.is_active})`);
    });
  }

  console.log('\n--- SEED COMPLETE ---');
}

seed().catch(console.error);
